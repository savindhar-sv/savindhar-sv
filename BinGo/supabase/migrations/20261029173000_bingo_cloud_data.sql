CREATE TABLE IF NOT EXISTS public.collection_schedules (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    neighborhood text NOT NULL
        CHECK (neighborhood IN (
            'RS Puram',
            'Gandhipuram',
            'Saibaba Colony',
            'Race Course',
            'Coimbatore'
        )),
    waste_type text NOT NULL CHECK (char_length(btrim(waste_type)) BETWEEN 1 AND 80),
    weekdays text[] NOT NULL CHECK (
        cardinality(weekdays) > 0
        AND weekdays <@ ARRAY[
            'Monday', 'Tuesday', 'Wednesday', 'Thursday',
            'Friday', 'Saturday', 'Sunday'
        ]::text[]
    ),
    pickup_window text NOT NULL CHECK (char_length(btrim(pickup_window)) BETWEEN 1 AND 80),
    source_url text NOT NULL CHECK (source_url ~ '^https://'),
    verified_at date NOT NULL,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS collection_schedules_neighborhood_active
    ON public.collection_schedules (neighborhood, verified_at DESC)
    WHERE is_active;

CREATE TABLE IF NOT EXISTS public.dropoff_locations (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    name text NOT NULL CHECK (char_length(btrim(name)) BETWEEN 1 AND 120),
    category text NOT NULL CHECK (category IN ('mcc', 'dry_kiosk', 'dustbin')),
    latitude double precision NOT NULL CHECK (latitude BETWEEN 10.8 AND 11.25),
    longitude double precision NOT NULL CHECK (longitude BETWEEN 76.75 AND 77.25),
    phone text CHECK (phone IS NULL OR phone ~ '^\+[1-9][0-9]{7,14}$'),
    source_url text NOT NULL CHECK (source_url ~ '^https://'),
    verified_at date NOT NULL,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS dropoff_locations_active_category
    ON public.dropoff_locations (category)
    WHERE is_active;

CREATE TABLE IF NOT EXISTS public.truck_locations (
    truck_id text PRIMARY KEY CHECK (truck_id ~ '^[A-Za-z0-9][A-Za-z0-9 -]{0,31}$'),
    latitude double precision NOT NULL CHECK (latitude BETWEEN 10.8 AND 11.25),
    longitude double precision NOT NULL CHECK (longitude BETWEEN 76.75 AND 77.25),
    accuracy_m double precision CHECK (accuracy_m IS NULL OR accuracy_m BETWEEN 0 AND 10000),
    neighborhood text NOT NULL
        CHECK (neighborhood IN (
            'RS Puram',
            'Gandhipuram',
            'Saibaba Colony',
            'Race Course',
            'Coimbatore'
        )),
    estimated_arrival_at timestamptz,
    updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.listings (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    owner_id uuid NOT NULL REFERENCES public.profiles (id) ON DELETE CASCADE,
    title text NOT NULL CHECK (char_length(btrim(title)) BETWEEN 1 AND 60),
    category text NOT NULL CHECK (category IN (
        'Books', 'Clothes', 'E-Waste', 'Furniture',
        'Home goods', 'Electronics', 'Kids'
    )),
    photo_path text,
    neighborhood text NOT NULL
        CHECK (neighborhood IN (
            'RS Puram',
            'Gandhipuram',
            'Saibaba Colony',
            'Race Course',
            'Coimbatore'
        )),
    status text NOT NULL DEFAULT 'available'
        CHECK (status IN ('available', 'completed', 'removed')),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CHECK (
        photo_path IS NULL
        OR photo_path = owner_id::text || '/' || id::text || '.jpg'
    )
);

CREATE INDEX IF NOT EXISTS listings_available_created
    ON public.listings (created_at DESC)
    WHERE status = 'available';

CREATE INDEX IF NOT EXISTS listings_owner_created
    ON public.listings (owner_id, created_at DESC);

CREATE OR REPLACE FUNCTION public.create_profile_for_new_user()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
    INSERT INTO public.profiles (id)
    VALUES (NEW.id)
    ON CONFLICT (id) DO NOTHING;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW EXECUTE FUNCTION public.create_profile_for_new_user();

CREATE OR REPLACE FUNCTION public.set_profile_updated_at()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS profiles_set_updated_at ON public.profiles;
CREATE TRIGGER profiles_set_updated_at
    BEFORE UPDATE ON public.profiles
    FOR EACH ROW EXECUTE FUNCTION public.set_profile_updated_at();

CREATE OR REPLACE FUNCTION public.set_listing_neighborhood()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
    IF auth.uid() IS NOT NULL THEN
        NEW.owner_id := auth.uid();
        SELECT p.neighborhood
          INTO NEW.neighborhood
          FROM public.profiles AS p
         WHERE p.id = auth.uid();

        IF NEW.neighborhood IS NULL THEN
            RAISE EXCEPTION 'Create a neighborhood profile before posting a listing.';
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS listings_set_neighborhood ON public.listings;
CREATE TRIGGER listings_set_neighborhood
    BEFORE INSERT OR UPDATE OF owner_id, neighborhood ON public.listings
    FOR EACH ROW EXECUTE FUNCTION public.set_listing_neighborhood();

REVOKE ALL ON FUNCTION public.create_profile_for_new_user() FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.set_profile_updated_at() FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.set_listing_neighborhood() FROM PUBLIC, anon, authenticated;

